def get_agent_profile(agent_type: AgentType) -> AgentProfile:
    """
    사원 프로필을 반환한다 (역할 소개, 분석프레임, 용도별 작성 규칙, 레벨 효과).
    모델 정보는 model_policy가 관리한다.
    """
    profile = _PROFILES.get(agent_type)
    if profile is None:
        raise InvalidAgentType()
    return profile
